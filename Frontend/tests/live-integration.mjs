// Run against the local fictional demo backend only. This resets synthetic state.
import assert from 'node:assert/strict'

const base = process.env.SENTINEL_API_BASE ?? 'http://127.0.0.1:8000'
async function call(path, method = 'GET', body, expected = [200]) {
  const response = await fetch(`${base}${path}`, { method, headers: { Accept: 'application/json', ...(body ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) })
  const value = await response.json()
  assert.ok(expected.includes(response.status), `${method} ${path}: ${response.status} ${JSON.stringify(value)}`)
  return value
}
const post = (path, body, expected = [200, 201]) => call(path, 'POST', body, expected)

await post('/api/v1/demo/reset')
const bootstrap = await call('/api/v1/demo/bootstrap')
assert.equal(bootstrap.astronaut.astronaut_id, 'DEMO-001')
assert.equal(bootstrap.habitat.habitat_id, 'HAB-01')
assert.ok(bootstrap.scheduled_assessments.some(item => item.is_due))

const symptom = await post('/api/v1/symptoms', { astronaut_id: 'DEMO-001', region_id: 'head', laterality: 'midline', severity: 3, onset: new Date(Date.now() - 45 * 60_000).toISOString() })
assert.ok(symptom.case_id)
const caseId = symptom.case_id
const observations = bootstrap.demo_inputs.ble_observations.map(item => ({ anchor_id: item.anchor_id, rssi_dbm: item.rssi_dbm, observed_at: new Date(Date.now() - item.age_seconds * 1000).toISOString() }))
const location = await post('/api/v1/location/estimate', { astronaut_id: 'DEMO-001', observations })
assert.equal(location.zone_id, 'crew-quarters')
assert.ok(location.confidence > 0)
const equipment = await post('/api/v1/equipment/recommend', { case_id: caseId, zone_id: location.zone_id, capability: 'blood_pressure' })
assert.equal(equipment.equipment_id, 'EQ-BP-01')
assert.deepEqual(equipment.route_zone_ids, ['crew-quarters', 'exercise', 'medical'])
const procedure = await call('/api/v1/procedures/PROC-BP-01')
assert.equal(procedure.steps.length, 6)
let session = await post('/api/v1/procedure-sessions', { case_id: caseId, procedure_id: 'PROC-BP-01', actor_id: 'DEMO-001', mode: 'self' })
for (const step of procedure.steps) {
  assert.equal(session.current_step_id, step.step_id)
  session = await post(`/api/v1/procedure-sessions/${encodeURIComponent(session.session_id)}/steps`, { step_id: step.step_id, completion_source: 'self_confirmed' })
}
assert.equal(session.status, 'completed')
const measurement = await post('/api/v1/measurements', { case_id: caseId, session_id: session.session_id, astronaut_id: 'DEMO-001', type: 'blood_pressure', value: { systolic: 118, diastolic: 76, pulse: 70 }, unit: 'mmHg', source: 'SIMULATED_MANUAL_ENTRY', observed_at: new Date().toISOString() })
assert.equal(measurement.case_state, 'monitoring')
assert.equal(measurement.validation.technical_checks_passed, true)
const persistedCase = await call(`/api/v1/cases/${encodeURIComponent(caseId)}`)
assert.equal(persistedCase.state, 'monitoring')
assert.equal(persistedCase.follow_up_status, 'scheduled')
const catalogue = await call('/api/v1/research/datasets')
assert.equal(catalogue.datasets.find(item => item.dataset_id === 'OSD-575')?.status, 'IMPORTED')
const research = await call('/api/v1/research/datasets/OSD-575/records?limit=1000')
assert.equal(research.total, 531)
assert.ok(research.records.some(item => typeof item.value === 'number' && item.unit && item.subject_id !== 'DEMO-001'))
assert.equal(research.data_category, 'NASA_RESEARCH')
const assayDataset = await call('/api/v1/research/datasets/OSD-656')
