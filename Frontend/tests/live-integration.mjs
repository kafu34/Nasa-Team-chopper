assert.equal(assay.total, 22)
assert.equal(assay.assay_records.length, 22)
assert.ok(assay.assay_records.every(item => item.analyte === 'il6' && item.measure === 'concentration_npq' && item.data_category === 'NASA_RESEARCH'))
